// TestMacosUserSeatbeltProfileEnforcesItsRules loads the generated profile with
// sandbox-exec and asks the kernel about every case above.
func TestMacosUserSeatbeltProfileEnforcesItsRules(t *testing.T) {
	requireMacosUserSeatbelt(t)
	f := seatbeltFixture(t)
	profile := seatbeltProfileFile(t, f)

	for _, tc := range seatbeltCases() {
		t.Run(tc.name, func(t *testing.T) {
			script := tc.script(f)
			bareOut, bareRC := runScript(t, script, nil)
			// THE CONTROL, always first. Every case is a claim that the SANDBOX is what
			// refused; a bare run that cannot do the thing either makes the case say
			// nothing at all, so it is a failure rather than a skip.
			if bareRC != 0 {
				t.Fatalf("the CONTROL failed: `%s` exits %d unsandboxed, so this case cannot "+
					"tell a policy refusal from a machine that never allowed it.\n"+
					"rule: %s\nwhy:  %s\noutput:\n%s", script, bareRC, tc.id, tc.why, bareOut)
			}
			sbOut, sbRC := runScript(t, script, []string{"/usr/bin/sandbox-exec", "-f", profile})

			switch tc.want {
			case wantRefused:
				if sbRC == 0 {
					t.Errorf("NOT REFUSED. `%s` succeeded under the profile.\n"+
						"rule: #seatbelt-test-id:%s#\nwhy:  %s\noutput:\n%s",
						script, tc.id, tc.why, sbOut)
				} else if tc.refusal != "" && !strings.Contains(sbOut, tc.refusal) {
					t.Errorf("REFUSED, but not with %q, so something other than the profile may "+
						"have refused it.\nrule: #seatbelt-test-id:%s#\nwhy:  %s\noutput:\n%s",
						tc.refusal, tc.id, tc.why, sbOut)
				}
			case wantAllowed:
				if !strings.Contains(sbOut, seatbeltOK) {
					t.Errorf("REFUSED, and should not have been. `%s` did not report %s under "+
						"the profile (rc %d).\nrule: #seatbelt-test-id:%s#\nwhy:  %s\noutput:\n%s",
						script, seatbeltOK, sbRC, tc.id, tc.why, sbOut)
				}
			case wantMarkerHidden:
				if !strings.Contains(bareOut, f.canaryWord) {
					t.Fatalf("the CONTROL failed: the canary's marker %q is absent from the "+
						"unsandboxed output, so its absence under the profile would prove "+
						"nothing.\noutput:\n%s", f.canaryWord, bareOut)
				}
				if strings.Contains(sbOut, f.canaryWord) {
					t.Errorf("NOT HIDDEN. The command line of a process outside the sandbox is "+
						"still readable from inside it (marker %q).\n"+
						"rule: #seatbelt-test-id:%s#\nwhy:  %s\noutput:\n%s",
						f.canaryWord, tc.id, tc.why, sbOut)
				}
			}
		})
	}
}

