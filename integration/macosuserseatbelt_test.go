// seatbeltFixture builds the tree the cases are written against and starts the canary.
//
// IT CANNOT BE t.TempDir(), and the reason is the profile rather than permissions: on
// darwin that is /var/folders, which the profile puts in the WRITABLE SET outright, so
// a workspace there would make every write case pass whether or not the workspace grant
// exists. Under /Users/Shared the workspace is inside the /Users read deny and is
// reachable only through the grants this suite is measuring.
func seatbeltFixture(t *testing.T) seatbeltFixtures {
	t.Helper()
	root, err := os.MkdirTemp(sharedUsersDir, "yolo-sb-")
	if err != nil {
		t.Fatalf("creating the fixture root under %s: %v", sharedUsersDir, err)
	}
	t.Cleanup(func() { _ = os.RemoveAll(root) })
	resolved, err := filepath.EvalSymlinks(root)
	if err != nil {
		t.Fatalf("resolving %s: %v", root, err)
	}
	f := seatbeltFixtures{
		root:     resolved,
		ws:       filepath.Join(resolved, "ws"),
		readonly: filepath.Join(resolved, "ws", "vendored"),
		outside:  filepath.Join(resolved, "outside"),
		neutral: filepath.Join("/private/var/tmp",
			fmt.Sprintf("yolo-sb-write-%d-%d", os.Getpid(), time.Now().UnixNano())),
	}
	t.Cleanup(func() { _ = os.Remove(f.neutral) })
	for _, d := range []string{f.ws, f.readonly, f.outside} {
		if err := os.MkdirAll(d, 0o755); err != nil {
			t.Fatalf("creating %s: %v", d, err)
		}
	}
	for path, content := range map[string]string{
		filepath.Join(f.ws, "seed"):        seatbeltOK + "\n",
		filepath.Join(f.outside, "secret"): "a sibling checkout's private file\n",
	} {
		if err := os.WriteFile(path, []byte(content), 0o644); err != nil {
			t.Fatalf("writing %s: %v", path, err)
		}
	}
	f.canaryPID, f.canaryWord = startSeatbeltCanary(t)
	return f
}

// startSeatbeltCanary spawns a process OUTSIDE the sandbox whose command line carries a
// word nothing else on the machine has, and returns its pid and that word.
//
// Outside is the whole point: `same-sandbox` re-allows the inspection of processes in
// the same sandbox, so a canary started from inside would be the case that is supposed
// to keep working rather than the one that must be refused.
func startSeatbeltCanary(t *testing.T) (int, string) {
	t.Helper()
	word := fmt.Sprintf("yolo-seatbelt-canary-%d-%d", os.Getpid(), time.Now().UnixNano())
	// A `while` loop rather than `sleep`, because a shell execs a single simple command
	// in place and the marker would go with the old argv.
	cmd := exec.Command("/bin/sh", "-c", "while :; do sleep 1; done # "+word)
	if err := cmd.Start(); err != nil {
		t.Fatalf("starting the argv canary: %v", err)
	}
	t.Cleanup(func() {
		_ = cmd.Process.Kill()
		_, _ = cmd.Process.Wait()
	})
	// Wait for it to be visible before any case reads it, so a slow fork is not
	// mistaken for a policy that hid it.
	deadline := time.Now().Add(10 * time.Second)
	for time.Now().Before(deadline) {
		out, _ := runScript(t, "ps -ww -o args= -p "+strconv.Itoa(cmd.Process.Pid)+" || true", nil)
		if strings.Contains(out, word) {
			return cmd.Process.Pid, word
		}
		time.Sleep(200 * time.Millisecond)
	}
	t.Fatalf("the argv canary (pid %d, marker %s) never became visible to `ps` "+
		"unsandboxed, so the cross-process cases have no control", cmd.Process.Pid, word)
	return 0, ""
}

// seatbeltProfileFile writes the generated profile where sandbox-exec can read it.
//
// The arguments are the ones BuildRunPlan passes (runplan.go): the workspace, the real
// sandbox home, and the workspace_readonly list — so the text under test is the text a
// launch would install, not a second profile written for the occasion. It is left in
// the temp dir on failure and its path is logged, because the first question about a
// surprising refusal is what the profile actually said.
func seatbeltProfileFile(t *testing.T, f seatbeltFixtures) string {
	t.Helper()
	profile := macosuser.SeatbeltProfile(f.ws, "", []string{"vendored"})
	path := filepath.Join(t.TempDir(), "session.sb")
	if err := os.WriteFile(path, []byte(profile), 0o644); err != nil {
		t.Fatalf("writing the profile to %s: %v", path, err)
	}
	t.Logf("Seatbelt profile under test (%s):\n%s", path, profile)
	return path
}

// runScript runs one shell script, optionally wrapped in a prefix argv, and returns its
// combined output and exit code.
//
// COMBINED, because the sandbox's refusal arrives on stderr ("Operation not permitted")
// and the case's evidence arrives on stdout; a failure message that carried only one of
// them would send a reader to the runner to see the other.
//
// Stdin is an empty PIPE and never the default /dev/null — see the file header:
// /dev/null is a device vnode, so `isatty(0)` on it is now a denied file-ioctl.
func runScript(t *testing.T, script string, prefix []string) (string, int) {
	t.Helper()
	ctx, cancel := context.WithTimeout(context.Background(), 60*time.Second)
	defer cancel()
	argv := append(append([]string{}, prefix...), "/bin/sh", "-c", script)
	cmd := exec.CommandContext(ctx, argv[0], argv[1:]...)
	// FROM "/", NEVER THE PACKAGE DIRECTORY. A runner checks this repo out under
	// /Users/runner/work, which the profile's /Users read deny covers with nothing to
	// re-allow it — so a shell inheriting that cwd can fail to resolve its own $PWD, and
	// the case would report a refusal it never asked for. "/" is read-allowed by the
	// base policy and is the same ground for the bare control.
	cmd.Dir = "/"
	cmd.Stdin = strings.NewReader("")
	out, err := cmd.CombinedOutput()
	if ctx.Err() != nil {
		t.Fatalf("`%s` did not finish within 60s", strings.Join(argv, " "))
	}
	rc := 0
	if err != nil {
		var ee *exec.ExitError
		if errors.As(err, &ee) {
			rc = ee.ExitCode()
		} else {
			t.Fatalf("running `%s`: %v", strings.Join(argv, " "), err)
		}
	}
	return string(out), rc
}

// sh single-quotes a path for /bin/sh. The fixture paths are ours and hold no quotes,
// but a script built by concatenation is a script that grows a space one day.
func sh(s string) string { return "'" + strings.ReplaceAll(s, "'", `'\''`) + "'" }
