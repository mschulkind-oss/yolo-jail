// TestMacosUserSeatbeltRegistryMatchesTheProfile is the greppability convention made
// mechanical, in both directions: a rule with no proof and no stated reason fails here,
// and so does a proof for a rule that no longer exists.
//
// It runs under -short, on Linux, WITHOUT the gate — which is the point. The machines
// that develop this repo cannot load a Seatbelt profile, so if this check waited for a
// Mac, a deny added today would sit unproven until the next nightly at the earliest.
func TestMacosUserSeatbeltRegistryMatchesTheProfile(t *testing.T) {
	// With delivered content, so the two G14 rules are in the text too, and a context mount of
	// each mode, so the three context rules are — otherwise the rules a launch with a pack or a
	// `mounts` entry generates are the ones this never checks.
	profile := macosuser.SeatbeltProfileWithContext("/Users/Shared/proj", "", []string{"vendored"},
		macosuser.ResolveHomeReadonly(macosuser.SandboxHome(), "/Users/Shared/proj",
			[]string{".claude"}, []string{".claude/skills", ".claude/CLAUDE.md"}),
		[]macosuser.ContextLink{
			{Dest: "/ctx/lib", Source: "/Users/Shared/ci/lib", Dir: true},
			{Dest: "/ctx/data", Source: "/Users/Shared/yolo/data", RW: true, Dir: true},
		})

	inProfile := map[string]bool{}
	for _, m := range seatbeltIDPattern.FindAllStringSubmatch(profile, -1) {
		inProfile[m[1]] = true
	}
	if len(inProfile) == 0 {
		t.Fatal("the profile carries no #seatbelt-test-id:…# markers at all — either the " +
			"convention was removed or this test is reading the wrong text")
	}

	registered := map[string]seatbeltRule{}
	for _, r := range seatbeltRules {
		if _, dup := registered[r.id]; dup {
			t.Errorf("rule %q is registered twice", r.id)
		}
		registered[r.id] = r
		if !inProfile[r.id] {
			t.Errorf("rule %q is registered here but is not in the profile; either the "+
				"directive was deleted and this entry outlived it, or the id was renamed "+
				"on one side only", r.id)
		}
	}
	for id := range inProfile {
		if _, ok := registered[id]; !ok {
			t.Errorf("the profile carries #seatbelt-test-id:%s# and nothing here claims it. "+
				"Add a case to seatbeltCases, or a seatbeltRules entry saying why no case "+
				"can prove it — an unregistered rule is one nobody will notice is untested.", id)
		}
	}

	proved := map[string]int{}
	for _, tc := range seatbeltCases() {
		if _, ok := registered[tc.id]; !ok {
			t.Errorf("case %q names rule %q, which is in no registry entry", tc.name, tc.id)
		}
		proved[tc.id]++
	}
	for _, r := range seatbeltRules {
		switch {
		case r.unproven == "" && proved[r.id] == 0:
			t.Errorf("rule %q claims to be proved at runtime and no case carries its id", r.id)
		case r.unproven != "" && proved[r.id] > 0:
			t.Errorf("rule %q is registered as unproven and %d case(s) carry its id; delete "+
				"the reason or delete the cases, but the file must not say both", r.id, proved[r.id])
		}
	}
}

// TestMacosUserSeatbeltContentControlsRunUnsandboxed runs the BARE CONTROL of every G14
// case on the machine that develops this repo, and checks the fixture survives them.
//
// WHY. Those scripts are built by string concatenation and nobody who writes them can run
// the suite above: it skips everywhere but a Mac. A quoting bug, or a control that forgets
// to restore what it moved, would surface as a broken control hours into the macOS job,
// which is the one run the whole exercise is for. What a Mac uniquely settles is the
// REFUSAL; whether each script does what its bare half claims does not need one. It
// asserts nothing about Seatbelt.
//
// Not behind requireMacosUserSeatbelt, so not in the vacuity ledger: it exercises no
// profile, and counting it would let the macOS job's "something ran" check pass without
// one. Only the home_content and context cases, because the older cases' controls lean on
// BSD `script` and macOS paths.
func TestMacosUserSeatbeltContentControlsRunUnsandboxed(t *testing.T) {
	if _, err := exec.LookPath("sh"); err != nil {
		t.Skip("no sh on PATH")
	}
	root, err := filepath.EvalSymlinks(t.TempDir())
	if err != nil {
		t.Fatal(err)
	}
	f := seatbeltTree(t, root)
	ran := 0
	_, gitErr := exec.LookPath("git")
	for _, tc := range seatbeltCases() {
		if !strings.HasPrefix(tc.name, "home_content_") && !strings.HasPrefix(tc.name, "context_") {
			continue
		}
		if tc.name == "context_git_inside_a_source" && gitErr != nil {
			t.Logf("%s: no git on PATH here, so its control cannot run", tc.name)
			continue
		}
		ran++
		out, rc := runScript(t, tc.script(f), nil)
		if rc != 0 {
			t.Errorf("%s: the bare control exits %d, so on a Mac this case would report a "+
				"broken control instead of measuring the profile:\n%s", tc.name, rc, out)
		}
		if tc.want == wantAllowed && !strings.Contains(out, seatbeltOK) {
			t.Errorf("%s: the bare control does not print %s:\n%s", tc.name, seatbeltOK, out)
		}
		// Every control must leave the fixture as it found it, or the next case measures a
		// different tree.
		for _, p := range []string{f.stateDir, filepath.Join(f.skills, "demo", "SKILL.md"), f.briefing,
			filepath.Join(f.ctxRO, "seed"), filepath.Join(f.ctxRW, "seed")} {
			if _, err := os.Stat(p); err != nil {
				t.Errorf("after %s's control, %s is gone (%v): the control does not restore "+
					"what it changed", tc.name, p, err)
			}
		}
		if target, err := os.Readlink(filepath.Join(f.linkDir, "data")); err != nil || target != f.ctxRO {
			t.Errorf("after %s's control, the link points at %q (%v), not %s", tc.name, target, err, f.ctxRO)
		}
		for _, p := range []string{filepath.Join(f.ctxRO, "probe"), filepath.Join(f.ctxRW, "probe"),
			filepath.Join(f.ws, "planted-link")} {
			if _, err := os.Lstat(p); err == nil {
				t.Errorf("after %s's control, %s is left behind", tc.name, p)
			}
		}
	}
	if ran == 0 {
		t.Fatal("no home_content case found; the prefix this test selects on has drifted")
	}
	// The fixture's rules must name the fixture's own staged content, spelled as resolved.
	for _, want := range []string{f.skills, f.briefing} {
		found := false
		for _, p := range f.content.Paths {
			found = found || p == want
		}
		if !found {
			t.Errorf("the fixture's content rules %v do not name %s", f.content.Paths, want)
		}
	}
}

// seatbeltIDPattern is the marker seatbelt.go embeds beside each deny. Spelled here
// rather than exported from that package: two independent readers of one convention is
// what makes a silent rename show up as a failure instead of as agreement.
var seatbeltIDPattern = regexp.MustCompile(`#seatbelt-test-id:([a-z0-9-]+)#`)

// ---------------------------------------------------------------------------
// The gate.
// ---------------------------------------------------------------------------

// seatbeltHost is what a policy assertion needs, which is much less than a launch
// needs: no _yolojail account, no sudo, no nix closure. A struct of FACTS so the
// decision stays pure and table-testable on Linux, where none of them can be produced —
// the same shape as macosUserHost, for the same reason.
type seatbeltHost struct {
	short          bool
	goos           string
	sandboxExec    bool // /usr/bin/sandbox-exec is there to load a profile with
	sharedWritable bool // /Users/Shared admits a fixture, which is where one must live
}

// gate returns the reason this host cannot assert the policy, or ok. Ordered
// most-fundamental-first so the reason a reader gets is the one to act on.
func (h seatbeltHost) gate() (reason string, ok bool) {
	switch {
	case h.short:
		return "skipping under -short: this loads a real Seatbelt profile", false
	case h.goos != "darwin":
		return fmt.Sprintf("Seatbelt is darwin-only and GOOS is %s — there is no "+
			"sandbox-exec here, so the profile is text and nothing more", h.goos), false
	case !h.sandboxExec:
		return "/usr/bin/sandbox-exec is absent, so no profile can be loaded. On a macOS " +
			"release that finally removed the Apple-deprecated tool this is the signal " +
			"that the whole backend needs rethinking, not a machine to fix", false
	case !h.sharedWritable:
		return fmt.Sprintf("%s does not admit a directory, and the fixture must live "+
			"there: the profile grants the workspace by path and denies the rest of "+
			"/Users, so a workspace under /var/folders would be inside the writable set "+
			"already and every write case would pass for the wrong reason",
			sharedUsersDir), false
	}
	return "", true
}

// probeSeatbeltHost measures the facts gate() decides on.
func probeSeatbeltHost() seatbeltHost {
	h := seatbeltHost{short: testing.Short(), goos: goruntime.GOOS}
	if h.goos != "darwin" {
		return h
	}
	if _, err := exec.LookPath("sandbox-exec"); err == nil {
		h.sandboxExec = true
	}
	if d, err := os.MkdirTemp(sharedUsersDir, "yolo-sb-probe-"); err == nil {
		h.sharedWritable = true
		_ = os.RemoveAll(d)
	}
	return h
}

// macosUserGateSeatbelt is this gate's name in the ledger. The verdict is computed PER
// GATE (macosUserVacuityVerdict), so a run that satisfied this cheap gate while every
// test behind the launch gate skipped is failed rather than counted green.
const macosUserGateSeatbelt = "seatbelt"

// requireMacosUserSeatbelt is the gate, and it files into the SAME ledger
// requireMacosUser uses (integration/macosusergate_test.go) so that a declared macOS
// run in which these all skip is still a failed run. A second ledger would be a second
// way for the suite to pass vacuously.
func requireMacosUserSeatbelt(t *testing.T) {
	t.Helper()
	if !macosUserTestNameOK(t.Name()) {
		t.Fatalf("%s does not start with %q; the macOS job selects this suite with "+
			"`-run '^%s'` and a test outside that pattern never runs",
			t.Name(), macosUserTestPrefix, macosUserTestPrefix)
	}
	reason := "the test skipped after passing the gate — see its own skip message"
	t.Cleanup(func() {
		macosUserTests.record(macosUserOutcomeFor(t.Name(), t.Skipped(), reason, macosUserGateSeatbelt))
	})
	if why, ok := probeSeatbeltHost().gate(); !ok {
		reason = why
		t.Skip("macos-user seatbelt: " + why)
	}
}

