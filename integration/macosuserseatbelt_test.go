// sharedUsersDir is where a fixture workspace has to live, and it is NOT
// macosuser.SharedRootDefault(): that is /Users/Shared/yolo, which `yolo macos-setup`
// creates and this suite deliberately does not require. /Users/Shared is stock macOS,
// mode 1777, present before anything of ours has run — which is what lets the policy
// assertions report on a Mac where the account setup has not happened or has failed.
const sharedUsersDir = "/Users/Shared"

// THE POLICY SUITE: a command run under the GENERATED profile, and the kernel's answer.
//
// WHY THIS FILE EXISTS. Sixteen tests in internal/macosuser pin what SeatbeltProfile
// emits — the clauses, the escaping, the last-match-wins ordering — and not one of them
// asks whether the emitted text denies anything. docs/research/agent-safehouse.md §8.1
// names that as the worst value-to-cost gap this backend has, one level up from the
// "pins the callee while the call site is unpinned" class AGENTS.md warns about: the
// tests pin the string, and nothing pins that the string does something. Agent
// Safehouse, the comparison that surfaced it, runs 389 bats cases that execute a
// command under their profile and assert the refusal.
//
// EVERY CASE HAS A CONTROL, and that is what makes it a measurement rather than a
// coincidence. `cat /Library/Keychains/…` failing inside the sandbox proves nothing on
// its own — it could be a missing file, a permission bit, SIP. So each case runs the
// SAME script twice: once bare, where it must succeed, and once under the profile,
// where it must be refused. A case whose bare control fails is reported as a broken
// control, loudly, rather than counted as a pass — a machine where the control stopped
// working is exactly the early warning the floating `macos-latest` label in
// .github/workflows/macos-user.yml exists to give.
//
// THE GATE IS NARROWER THAN A LAUNCH'S, deliberately. requireMacosUser needs the
// _yolojail account, a shared root and passwordless sudo, because it launches. This
// needs `sandbox-exec` and a writable /Users/Shared, because it loads a profile and
// runs /bin/sh under it. So the policy suite still reports on a Mac where
// `yolo macos-setup` has not run or has failed — which is the one machine state where
// knowing whether the profile still denies things is most useful.
//
// WHAT THIS SUITE IS NOT. It is not a launch: nothing here runs `yolo`, builds a nix
// closure, or becomes the sandbox user. The profile it loads is the one BuildRunPlan
// would install, generated by the same function with the same arguments, and the
// separate question of whether a launch actually hands that profile to the agent is
// pinned by internal/macosuser/launchconfinement_test.go.
//
// STDIN IS A PIPE FOR EVERY RUN, and it is not incidental. Go gives a child with no
// Stdin the /dev/null DEVICE, which is a vnode — so `isatty(0)` on it is a
// `file-ioctl` on a path, which the profile now denies, and the caller sees EPERM where
// it expected ENOTTY. A pipe has no path and never reaches that check. Anything that
// treats an ioctl error as fatal rather than as "not a terminal" would fail here for a
// reason that has nothing to do with the case under test.

// ---------------------------------------------------------------------------
// The registry: every #seatbelt-test-id: in the profile, and what proves it.
// ---------------------------------------------------------------------------

// seatbeltRule is one rule id in the generated profile. `unproven` is empty when at
// least one runtime case below carries the id, and otherwise says why no case can —
// which is the point of the registry: the negative space is WRITTEN DOWN instead of
// being the silence left by a case nobody wrote.
type seatbeltRule struct {
	id       string
	unproven string
}

// seatbeltRules must name every id the profile carries, and only those.
