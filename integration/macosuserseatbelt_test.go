// seatbeltWant is what the SANDBOXED run must show. The bare run is the control and its
// expectation is fixed: it must succeed, and for markerHidden it must show the marker.
type seatbeltWant int

const (
	// wantRefused: the sandboxed run exits non-zero. The bare run exits zero.
	wantRefused seatbeltWant = iota
	// wantAllowed: the sandboxed run prints seatbeltOK, like the bare run. A marker
	// rather than an exit code because several probes here exit zero having done
	// nothing (`script` reports its own status, not its child's).
	wantAllowed
	// wantMarkerHidden: the bare run prints the fixture's marker and the sandboxed run
	// does not. The shape cross-process argv needs, where the refusal is invisible —
	// `ps` prints a shorter line rather than failing.
	wantMarkerHidden
)

// seatbeltOK is what a wantAllowed script prints when the operation really happened.
const seatbeltOK = "SEATBELT_OK"

// seatbeltFixtures is the tree every script is written against. ws is the granted
// workspace, root its (traversal-only) parent, outside a sibling of ws under that
// parent — a real checkout beside the granted one, which is the case the (literal)
// ancestor grants exist to keep denied.
type seatbeltFixtures struct {
	root     string // /Users/Shared/yolo-sb-XXXX — traversal only
	ws       string // <root>/ws                   — granted, read+write
	readonly string // <root>/ws/vendored          — config.workspace_readonly
	outside  string // <root>/outside              — denied
	// neutral is a path under /private/var/tmp: READ-ALLOWED by the base policy and
	// outside the writable set. It is what isolates the write deny — a probe under
	// /Users would be refused by the read deny too, and the case could not say which
	// directive did it.
	neutral    string
	canaryPID  int    // a process spawned OUTSIDE the sandbox
	canaryWord string // a word on that process's command line
	// THE STAGED CONTENT (G14), laid out where a launch with the claude pack puts it: in
	// the workspace sidecar, which ~/.claude is a symlink into. stateDir is the agent's
	// own state directory there, skills and briefing the two things the bootstrap copied
	// into it, and content the rules the profile carries for them — computed by the same
	// resolver BuildRunPlan calls, with the real sandbox home, so nothing is written
	// outside the fixture and the text under test is what a launch would install.
	stateDir string // <ws>/.yolo/home/claude — the agent's, and must stay writable
	skills   string // <stateDir>/skills          — staged, write-protected
	briefing string // <stateDir>/CLAUDE.md       — staged, write-protected
	content  macosuser.HomeReadonly
	// THE CONTEXT MOUNTS (context-mounts.md §3), laid out as a launch delivers them: two
	// sources under one traversal-only directory BESIDE the workspace, so only the rules this
	// fixture's links add can open them, and a sibling of both that nothing grants. linkDir is
	// a stand-in for the context dir: outside the writable set (the profile's root write deny
	// is what keeps a link there from being replaced; root ownership is the launch's half,
	// asserted by integration/macosusercontextmounts_test.go) and read-allowed by the base
	// policy, holding one link to the read-only source and one to the ungranted sibling.
	ctxRoot    string // <root>/ctx               — traversal only
	ctxRO      string // <root>/ctx/ro            — read-only context mount, holds a git repo
	ctxRW      string // <root>/ctx/rw            — read-write context mount
	ctxSibling string // <root>/ctx/other         — granted by nothing
	linkDir    string // /private/var/tmp/yolo-sb-ctx-…   — the links
	ctxLinks   []macosuser.ContextLink
}

type seatbeltCase struct {
	name string
	id   string // the #seatbelt-test-id: in the profile this proves
	// why the case is written the way it is — printed on failure, because a policy
	// refusal with no explanation is a line nobody can act on.
	why    string
	script func(seatbeltFixtures) string
	want   seatbeltWant
	// refusal, when set, is text a wantRefused run's output must carry — "Operation not
	// permitted", the EPERM that proves the PROFILE refused rather than the file mode (EACCES,
	// "Permission denied"), which is the distinction declaration-parity.md §6.1 probe 3 drew.
	refusal string
}

