// A hung daemon on a Mac: the restart names the daemon this Nix runs, and determinate-nixd is
// named only on Determinate Nix, whose daemon it is.
func TestTheMacNixDaemonTimeoutNamesTheDaemonItIs(t *testing.T) {
	const hung = "Nix daemon: store operation timed out (daemon may be hung)"
	bothPlists := map[string]string{upstreamPlist: "", determinatePlist: ""}

	r, out := nixMachine{mac: true, version: determinateNixVersion, store: ExecResult{Ran: true, Timeout: true},
		files: bothPlists}.nixSection(t)
	f, ok := findingFor(r, hung)
	if !ok || f.Status != "fail" {
		t.Fatalf("no timeout FAIL:\n%s", out)
	}
	if want := "sudo launchctl kickstart -k system/" + storage.DeterminateNixDaemonLabel; !strings.Contains(f.Note, want) {
		t.Errorf("the Determinate Nix remedy lacks %q:\n%s", want, f.Note)
	}
	// The guide no longer covers Determinate Nix, so a pointer into it is a dead end.
	if strings.Contains(f.Note, "userguide/") {
		t.Errorf("the Determinate Nix remedy points into the guide, which no longer covers it:\n%s", f.Note)
	}

	r, out = nixMachine{mac: true, version: upstreamNixVersion, store: ExecResult{Ran: true, Timeout: true},
		files: map[string]string{upstreamPlist: ""}}.nixSection(t)
	f, ok = findingFor(r, hung)
	if !ok || f.Status != "fail" {
		t.Fatalf("no timeout FAIL:\n%s", out)
	}
	if !strings.Contains(f.Note, "sudo launchctl kickstart -k system/"+storage.UpstreamNixDaemonLabel) {
		t.Errorf("the upstream Nix remedy must restart its own daemon:\n%s", f.Note)
	}
	if strings.Contains(strings.ToLower(f.Note), "determinate") {
		t.Errorf("an upstream Nix user has no determinate-nixd:\n%s", f.Note)
	}
}

// A refused connection on a Mac was a dead end, nix's first stderr line and nothing else. It now
// carries the restart for this Nix's daemon, as the Linux branch does.
func TestTheMacNixDaemonConnectionFailureNamesTheRestart(t *testing.T) {
	refused := ExecResult{Ran: true, RC: 1, Stderr: "error: cannot connect to socket at " +
		"'/nix/var/nix/daemon-socket/socket': Connection refused\n"}
	for version, label := range map[string]string{
		determinateNixVersion: storage.DeterminateNixDaemonLabel,
		upstreamNixVersion:    storage.UpstreamNixDaemonLabel,
	} {
		r, out := nixMachine{mac: true, version: version, store: refused,
			files: map[string]string{upstreamPlist: "", determinatePlist: ""}}.nixSection(t)
		f, ok := findingFor(r, "Nix daemon: connection failed")
		if !ok || f.Status != "fail" {
			t.Fatalf("no connection FAIL:\n%s", out)
		}
		if !strings.Contains(f.Note, "Connection refused") ||
			!strings.Contains(f.Note, "sudo launchctl kickstart -k system/"+label) {
			t.Errorf("%s: the remedy must keep nix's line and restart system/%s:\n%s", version, label, f.Note)
		}
	}
}
