// What the two Nix distributions leave on a machine, as far as the Nix sections' hints care.
// The `--version` lines are nix-src src/libmain/shared.cc's, and the nix.conf bodies are what
// each installer writes.
const (
	determinateNixVersion = "nix (Determinate Nix 3.22.5) 2.35.2\n"
	upstreamNixVersion    = "nix (Nix) 2.34.7\n"
	lixNixVersion         = "nix (Lix, like Nix) 2.91.1\n"

	// determinate-nixd's own nix.conf, which it replaces; user settings go in nix.custom.conf.
	determinateManagedNixConf = "# DETERMINATE NIX CONFIG\n# do not modify! this file will be replaced!\n\n" +
		"!include nix.custom.conf\n"
	// The Determinate installer's, installing upstream Nix.
	determinateInstallerNixConf = "# Generated by https://github.com/DeterminateSystems/nix-installer.\n\n" +
		"build-users-group = nixbld\nextra-experimental-features = nix-command flakes\n!include nix.custom.conf\n"
	// The official nixos.org script's: no include at all.
	officialInstallerNixConf = "build-users-group = nixbld\n"

	// Host-root-relative paths of the files the hints read.
	nixConfFile      = "etc/nix/nix.conf"
	upstreamPlist    = "Library/LaunchDaemons/org.nixos.nix-daemon.plist"
	determinatePlist = "Library/LaunchDaemons/systems.determinate.nix-daemon.plist"
	nixHookPlist     = "Library/LaunchDaemons/systems.determinate.nix-installer.nix-hook.plist"
)

var (
	trustedStore   = ExecResult{Ran: true, RC: 0, Stdout: "Store URL: daemon\nVersion: 2.35.2\nTrusted: 1\n"}
	untrustedStore = ExecResult{Ran: true, RC: 0, Stdout: "Store URL: daemon\nVersion: 2.35.2\nTrusted: 0\n"}
)

// nixMachine is a fake host for the Nix sections: what `nix --version`, `nix store info` and
// `nix config show` answer, and the files under the host root the sections read /etc/nix and
// /Library/LaunchDaemons from (root-relative path → content). Off macOS it has systemctl.
type nixMachine struct {
	mac, inJail bool
	version     string
	store       ExecResult
	config      string
	files       map[string]string
	// links are symbolic links under the host root (root-relative path → root-relative target),
	// made after files: a nix-darwin or NixOS /etc/nix/nix.conf is one into the Nix store.
	links map[string]string
	// user is the account check runs as, testUser when "".
	user string
}

// testUser is the account a nixMachine's check runs as unless it names another.
const testUser = "alice"

func (m nixMachine) options(t *testing.T, out *bytes.Buffer) *Options {
	t.Helper()
	// Resolved where it is minted: on macOS t.TempDir() is under /var/folders, a symlink to
	// /private/var/folders, and the generated-nix.conf probe compares resolved paths.
	root, err := filepath.EvalSymlinks(t.TempDir())
	must(t, err)
	for rel, body := range m.files {
		p := filepath.Join(root, rel)
		must(t, os.MkdirAll(filepath.Dir(p), 0o755))
		must(t, os.WriteFile(p, []byte(body), 0o644))
	}
	for rel, target := range m.links {
		p := filepath.Join(root, rel)
		must(t, os.MkdirAll(filepath.Dir(p), 0o755))
		must(t, os.Symlink(filepath.Join(root, target), p))
	}
	o := &Options{IsMacOS: m.mac, Stdout: out, IsTTYStdout: func() bool { return false }, nixHostRoot: root}
	fillDefaults(o)
	o.currentUser = func() string {
		if m.user != "" {
			return m.user
		}
		return testUser
	}
	o.Getenv = func(k string) string {
		if k == "YOLO_VERSION" && m.inJail {
			return "9.9.9-test"
		}
		return ""
	}
	o.LookPath = func(name string) (string, bool) {
		return "/usr/bin/" + name, name == "nix" || (!m.mac && name == "systemctl")
	}
	o.Exec = func(argv []string, _ string, _ []string, _ time.Duration) ExecResult {
		switch {
		case slices.Equal(argv, []string{"nix", "--version"}):
			return ExecResult{Ran: true, RC: 0, Stdout: m.version}
		case slices.Equal(argv, nixCmdArgv("store", "info")):
			return m.store
		case slices.Equal(argv, nixCmdArgv("config", "show")):
			return ExecResult{Ran: true, RC: 0, Stdout: m.config}
		}
		return ExecResult{Ran: false}
	}
	return o
}

// nixSection runs the Nix section on m.
func (m nixMachine) nixSection(t *testing.T) (*reporter, string) {
	t.Helper()
	var out bytes.Buffer
	o := m.options(t, &out)
	r := newReporter(&out, false)
	o.sectionNix(r)
	return r, out.String()
}

// Which Nix this is is asked ONCE per check. Here every reader of it runs: the version row, the
// untrusted hint's file and restart, and the auto-GC section's verdict on a min-free of 0.
func TestWhichNixIsAskedOncePerCheck(t *testing.T) {
	var out bytes.Buffer
	o := nixMachine{mac: true, version: determinateNixVersion, store: untrustedStore,
		config: "min-free = 0\n"}.options(t, &out)
	exec, versions := o.Exec, 0
	o.Exec = func(argv []string, dir string, env []string, d time.Duration) ExecResult {
		if slices.Equal(argv, []string{"nix", "--version"}) {
			versions++
		}
		return exec(argv, dir, env, d)
	}
	r := newReporter(&out, false)
	o.sectionNix(r)
	o.sectionAutoGC(r)
	if !strings.Contains(out.String(), "nix.custom.conf") || !strings.Contains(out.String(), "determinate-nixd") {
		t.Fatalf("the hints did not read the distribution:\n%s", out.String())
	}
	if versions != 1 {
		t.Errorf("`nix --version` ran %d times in one check, want once", versions)
	}
}

