// The untrusted-user hint is the one fix for THIS install, as a command to paste: the file a
// trusted-users line takes effect in, and the restart for the daemon this Nix runs. Determinate
// Nix replaces /etc/nix/nix.conf, so it is never named there; upstream Nix takes the line in
// nix.custom.conf only when nix.conf includes that file and does not set trusted-users again
// after the include (the last assignment wins), and in nix.conf itself otherwise. Nothing asks
// for an include line to be appended any more: on upstream Nix, appending to nix.conf works alone.
//
// THE LINE ADDS, IT NEVER ASSIGNS. A `trusted-users = …` line is an assignment and replaces the
// list: measured with nix 2.34.8, `trusted-users = root alice` then an appended
// `trusted-users = root bob` trusts `root bob`, so alice is dropped. That is the runbook's own
// machine (mac-sandvault-session.md §5, the "sets trusted-users after the include" case below),
// where the hint told sandvault-matt to append a line that untrusted matt. `extra-trusted-users`
// appends to the list (measured: `root alice bob`).
func TestTheUntrustedHintNamesThisNixsFileAndRestart(t *testing.T) {
	const custom, conf = "/etc/nix/nix.custom.conf", "/etc/nix/nix.conf"
	const trustCmd = `echo "extra-trusted-users = ` + testUser + `" | sudo tee -a `
	cases := []struct {
		name, version string
		files         map[string]string
		file, label   string
	}{
		{"Determinate Nix, the upstream daemon's plist left behind", determinateNixVersion,
			map[string]string{nixConfFile: determinateManagedNixConf, upstreamPlist: "", determinatePlist: "",
				nixHookPlist: ""},
			custom, storage.DeterminateNixDaemonLabel},
		{"Determinate Nix, nothing readable", determinateNixVersion, nil,
			custom, storage.DeterminateNixDaemonLabel},
		{"upstream Nix from the Determinate installer", upstreamNixVersion,
			map[string]string{nixConfFile: determinateInstallerNixConf, upstreamPlist: "", nixHookPlist: ""},
			custom, storage.UpstreamNixDaemonLabel},
		{"upstream Nix from the official installer", upstreamNixVersion,
			map[string]string{nixConfFile: officialInstallerNixConf, upstreamPlist: ""},
			conf, storage.UpstreamNixDaemonLabel},
		{"upstream Nix whose nix.conf sets trusted-users after the include", upstreamNixVersion,
			map[string]string{nixConfFile: "!include /etc/nix/nix.custom.conf\ntrusted-users = root matt\n",
				upstreamPlist: ""},
			conf, storage.UpstreamNixDaemonLabel},
		{"upstream Nix, the Determinate daemon's plist left behind", upstreamNixVersion,
			map[string]string{nixConfFile: officialInstallerNixConf, upstreamPlist: "", determinatePlist: ""},
			conf, storage.UpstreamNixDaemonLabel},
		{"upstream Nix, nothing readable", upstreamNixVersion, nil,
			conf, storage.UpstreamNixDaemonLabel},
	}
	for _, tc := range cases {
		t.Run(tc.name, func(t *testing.T) {
			r, out := nixMachine{mac: true, version: tc.version, store: untrustedStore, files: tc.files}.nixSection(t)
			f, ok := findingFor(r, "Nix daemon: connected but user is NOT trusted")
			if !ok || f.Status != "warn" {
				t.Fatalf("no untrusted WARN:\n%s", out)
			}
			if !strings.Contains(f.Note, trustCmd+tc.file) {
				t.Errorf("the hint must say `%s%s`:\n%s", trustCmd, tc.file, f.Note)
			}
			if !strings.Contains(f.Note, "sudo launchctl kickstart -k system/"+tc.label) {
				t.Errorf("the hint must restart system/%s:\n%s", tc.label, f.Note)
			}
			if strings.Contains(f.Note, `"trusted-users =`) {
				t.Errorf("a `trusted-users =` line replaces the list and drops whoever is on it:\n%s", f.Note)
			}
			if strings.Contains(f.Note, "!include") {
				t.Errorf("the hint must not ask for an include line:\n%s", f.Note)
			}
			if tc.file == conf && strings.Contains(f.Note, "nix.custom.conf") {
				t.Errorf("a line in nix.custom.conf would not take effect here:\n%s", f.Note)
			}
			if tc.version == determinateNixVersion && strings.Contains(f.Note, conf) {
				t.Errorf("a Determinate Nix user must never be sent to the nix.conf it replaces:\n%s", f.Note)
			}
		})
	}
}

// The hint names the account check runs as, not `$(whoami)`, which expands in whatever shell the
// human pastes it into. On the macos-user backend check runs inside the sandbox as the dedicated
// macOS account, which has no sudo, so the human pastes the command in their own terminal and
// `$(whoami)` added their own, already trusted, user: the warning never cleared.
func TestTheUntrustedHintNamesTheAccountCheckRunsAs(t *testing.T) {
	r, out := nixMachine{mac: true, inJail: true, user: "sandbox-acct", version: upstreamNixVersion,
		store: untrustedStore, files: map[string]string{nixConfFile: officialInstallerNixConf, upstreamPlist: ""}}.nixSection(t)
	f, ok := findingFor(r, "Nix daemon: connected but user is NOT trusted")
	if !ok {
		t.Fatalf("no untrusted WARN:\n%s", out)
	}
	if !strings.Contains(f.Note, `echo "extra-trusted-users = sandbox-acct" | sudo tee -a /etc/nix/nix.conf`) {
		t.Errorf("the hint must add the account check runs as:\n%s", f.Note)
	}
	if strings.Contains(f.Note, "whoami") {
		t.Errorf("`$(whoami)` names whoever pastes the command, not the account the daemon refused:\n%s", f.Note)
	}
}

// A nix-darwin or NixOS /etc/nix/nix.conf is generated from the system configuration: a symlink
// into the Nix store (/etc/nix/nix.conf -> /etc/static/nix/nix.conf -> /nix/store/…-nix.conf) with
// no include. A line appended there fails on the read-only store or is discarded by the next
// rebuild, so the fix is the configuration's nix.settings, and no hint says `tee -a` there. A
// nix.conf linked anywhere else (a dotfiles checkout) still takes the appended line.
func TestTheHintsOnAGeneratedNixConfSetTheConfiguration(t *testing.T) {
	generated := map[string]string{nixConfFile: "etc/static/nix/nix.conf", "etc/static/nix/nix.conf": "nix/store/x-nix.conf"}
	storeConf := map[string]string{"nix/store/x-nix.conf": "trusted-users = root matt\n", upstreamPlist: ""}

	r, out := nixMachine{mac: true, version: upstreamNixVersion, store: untrustedStore,
		files: storeConf, links: generated}.nixSection(t)
	f, ok := findingFor(r, "Nix daemon: connected but user is NOT trusted")
	if !ok {
		t.Fatalf("no untrusted WARN:\n%s", out)
	}
	for _, want := range []string{"nix.settings.trusted-users", "rebuild", testUser,
		"sudo launchctl kickstart -k system/" + storage.UpstreamNixDaemonLabel} {
		if !strings.Contains(f.Note, want) {
			t.Errorf("the trust hint on a generated nix.conf lacks %q:\n%s", want, f.Note)
		}
	}
	if strings.Contains(f.Note, "tee -a") {
		t.Errorf("a line appended to a generated nix.conf does not last:\n%s", f.Note)
	}

	r, out = nixMachine{version: upstreamNixVersion, config: "min-free = 0\n",
		files: storeConf, links: generated}.autoGCSection(t)
	f, ok = findingFor(r, minFreeOffRow)
	if !ok {
		t.Fatalf("no min-free WARN:\n%s", out)
	}
	for _, want := range []string{"nix.settings.min-free", "nix.settings.max-free", "rebuild"} {
		if !strings.Contains(f.Note, want) {
			t.Errorf("the auto-GC remedy on a generated nix.conf lacks %q:\n%s", want, f.Note)
		}
	}
	if strings.Contains(f.Note, "Add to /etc/nix") {
		t.Errorf("a line added to a generated nix.conf does not last:\n%s", f.Note)
	}

	// Linked, but not into the store: the file the link names takes the line.
	r, out = nixMachine{mac: true, version: upstreamNixVersion, store: untrustedStore,
		files: map[string]string{"home/matt/dotfiles/nix.conf": officialInstallerNixConf, upstreamPlist: ""},
		links: map[string]string{nixConfFile: "home/matt/dotfiles/nix.conf"}}.nixSection(t)
	f, ok = findingFor(r, "Nix daemon: connected but user is NOT trusted")
	if !ok {
		t.Fatalf("no untrusted WARN:\n%s", out)
	}
	if !strings.Contains(f.Note, "sudo tee -a /etc/nix/nix.conf") || strings.Contains(f.Note, "nix.settings") {
		t.Errorf("a nix.conf linked outside the store takes an appended line:\n%s", f.Note)
	}
}

