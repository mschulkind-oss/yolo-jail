// BaselineActions are the buttons the owner's current on_request script offers, in the
// order it passes them to notify-send (native-notification-gallery.md, the baseline).
var BaselineActions = []string{"Allow once", "Allow 1h", "Deny"}

type galleryRequest struct {
	ID            string   `json:"id"`
	Source        string   `json:"source"`
	Workspace     string   `json:"workspace"`
	Set           string   `json:"set"`
	Command       string   `json:"command"`
	Repo          string   `json:"repo"`
	Filed         string   `json:"filed"`
	Expires       string   `json:"expires"`
	State         string   `json:"state"`
	Headline      string   `json:"headline"`
	Description   string   `json:"description"`
	NeedsApproval []string `json:"needs_approval"`
	HookFailure   string   `json:"hook_failure"`
	HookOutput    string   `json:"hook_output"`
}

type galleryTile struct {
	Fixture
	Req      *galleryRequest
	Platform map[string][]Evidence
}

type galleryFamily struct {
	Name  string
	Tiles []galleryTile
}

// Gallery renders the static gallery page from the fixtures. Every string a fixture holds is
// untrusted request text, so the page is built with html/template's contextual escaping and
// carries no script. The output is deterministic: the same fixtures give the same bytes.
func Gallery(fs []Fixture) ([]byte, error) {
	byFamily := map[string][]galleryTile{}
	counts := map[string]int{}
	for _, f := range fs {
		t := galleryTile{Fixture: f, Platform: map[string][]Evidence{}}
		if len(f.Request) != 0 {
			var r galleryRequest
			if err := json.Unmarshal(f.Request, &r); err != nil {
				return nil, err
			}
			t.Req = &r
		}
		for _, e := range f.Evidence {
			t.Platform[e.Platform] = append(t.Platform[e.Platform], e)
			counts[e.Platform+" "+e.Kind]++
		}
		byFamily[f.Family] = append(byFamily[f.Family], t)
	}
	var families []galleryFamily
	for _, name := range Families {
		if tiles := byFamily[name]; len(tiles) > 0 {
			sort.SliceStable(tiles, func(i, j int) bool { return tiles[i].ID < tiles[j].ID })
			families = append(families, galleryFamily{Name: name, Tiles: tiles})
		}
	}
	var keys []string
	for k := range counts {
		keys = append(keys, k)
	}
	sort.Strings(keys)
	type count struct {
		Key string
		N   int
	}
	var summary []count
	for _, k := range keys {
		summary = append(summary, count{k, counts[k]})
	}
	var buf bytes.Buffer
	err := galleryTemplate.Execute(&buf, map[string]any{
		"Families": families, "Total": len(fs), "Summary": summary, "Actions": BaselineActions, "Order": Platforms,
	})
	return buf.Bytes(), err
}

